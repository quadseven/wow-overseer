"""Build app/fonts/: the text font and a subset of the icon fonts, from upstream files.

The page used to load a font stylesheet from one third-party host and two icon
stylesheets from another (about 175 KB of font files, blocking first paint).
This tool writes what the page needs into app/fonts/, so nothing leaves the
app's own mount.

Usage:
  python3 tools/vendor_icons.py --upstream DIR [--out app/fonts]

DIR holds the upstream files, as published:
  regular-style.css, regular-Phosphor.woff2   Phosphor Icons 2.1.1, regular
  fill-style.css,    fill-Phosphor-Fill.woff2 Phosphor Icons 2.1.1, fill
  inter-latin.woff2                           Inter, the latin subset (variable weight), cut
                                              further to the text the app draws

It needs fontTools and brotli (`pip install fonttools brotli`), only to run it;
nothing at runtime and no test imports them. It scans the app's sources for the
icon classes they use (`used_icons`), keeps just those glyphs in each icon
font, and writes phosphor.woff2, phosphor-fill.woff2, inter-latin.woff2 and
fonts.css. tests/test_app_fonts.py fails when a source names an icon the
subset lacks, so adding an icon means running this tool again.

Licenses: Phosphor Icons is MIT, Inter is the SIL Open Font License 1.1; their
notices sit beside the fonts (app/fonts/LICENSE-*.txt).
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent.parent

# Where icon classes are written: markup in the app and in the Python that
# serves it. Tests, the tools and the submodule do not count.
SOURCE_SUFFIXES = (".js", ".py", ".html")
SKIP_DIRS = {
    "mod-overseer",
    "node_modules",
    ".git",
    "tests",
    "tools",
    "__pycache__",
    "fonts",
}

TOKEN = re.compile(r"\bph-([a-z0-9]+(?:-[a-z0-9]+)*)\b")
# shell.js builds its nav classes from bare names: icon: "pulse".
NAV_ICON = re.compile(r"""\bicon:\s*["']([a-z0-9]+(?:-[a-z0-9]+)*)["']""")
# Words that follow `ph-` but are style names, not icons.
NOT_ICONS = {"fill", "bold", "light", "thin", "duotone"}

# The text the app draws: Basic Latin, Latin-1, general punctuation (dashes,
# quotes, bullets, ellipsis), arrows, minus, euro and trademark. A name outside
# this falls back to the system font for that glyph only.
INTER_POINTS = (
    list(range(0x20, 0x7F))
    + list(range(0xA0, 0x100))
    + list(range(0x2010, 0x2028))
    + [
        0x2030,
        0x2032,
        0x2033,
        0x2039,
        0x203A,
        0x20AC,
        0x2122,
        0x2190,
        0x2191,
        0x2192,
        0x2193,
        0x2212,
        0x2215,
        0x25CF,
    ]
)

RULE = re.compile(
    r'\.(ph|ph-fill)\.ph-([a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)";\s*\}'
)


def used_icons(root: pathlib.Path = HERE) -> set[str]:
    """Every icon name (without `ph-`) the app's sources can put on a page."""
    names: set[str] = set()
    for path in root.rglob("*"):
        if path.suffix not in SOURCE_SUFFIXES or not path.is_file():
            continue
        rel = path.relative_to(root).parts
        if any(part in SKIP_DIRS for part in rel[:-1]):
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        names.update(m.group(1) for m in TOKEN.finditer(text))
        if rel[-1] == "shell.js":
            names.update(m.group(1) for m in NAV_ICON.finditer(text))
    return names - NOT_ICONS


def codepoints(css: str, style: str) -> dict[str, int]:
    """{icon name: codepoint} for the rules of one style (`ph` or `ph-fill`)."""
    return {
        name: int(code, 16) for sel, name, code in RULE.findall(css) if sel == style
    }


def local_css(regular: dict[str, int], fill: dict[str, int]) -> str:
    """The one stylesheet the page links: text font, icon fonts, used glyphs."""
    base = (
        "  speak: never;\n  font-style: normal;\n  font-weight: normal;\n  font-variant: normal;\n"
        "  text-transform: none;\n  line-height: 1;\n  letter-spacing: 0;\n"
        "  -webkit-font-smoothing: antialiased;\n  -moz-osx-font-smoothing: grayscale;\n"
    )
    out = [
        "/* Generated by tools/vendor_icons.py; do not edit. Fonts: Inter (OFL 1.1), Phosphor Icons (MIT). */\n",
        '@font-face {\n  font-family: "Inter";\n  font-style: normal;\n  font-weight: 400 500;\n'
        '  font-display: swap;\n  src: url(inter-latin.woff2) format("woff2");\n}\n',
        '@font-face {\n  font-family: "Phosphor";\n  src: url(phosphor.woff2) format("woff2");\n'
        "  font-weight: normal;\n  font-style: normal;\n  font-display: block;\n}\n",
        '@font-face {\n  font-family: "Phosphor-Fill";\n  src: url(phosphor-fill.woff2) format("woff2");\n'
        "  font-weight: normal;\n  font-style: normal;\n  font-display: block;\n}\n",
        '.ph {\n  font-family: "Phosphor" !important;\n' + base + "}\n",
        '.ph-fill {\n  font-family: "Phosphor-Fill" !important;\n' + base + "}\n",
    ]
    for sel, table in ((".ph", regular), (".ph-fill", fill)):
        for name in sorted(table):
            out.append(
                '%s.ph-%s:before {\n  content: "\\%x";\n}\n' % (sel, name, table[name])
            )
    return "".join(out)


def subset(
    src: pathlib.Path,
    dst: pathlib.Path,
    points: list[int],
    weights: tuple[int, int] | None = None,
) -> None:
    """Keep only `points` of `src`; a variable font is also cut to `weights`."""
    import io

    from fontTools import subset as ft
    from fontTools.ttLib import TTFont

    font = TTFont(str(src))
    options = ft.Options()
    options.layout_features = ["*"]
    options.notdef_outline = True
    subsetter = ft.Subsetter(options)
    subsetter.populate(unicodes=points)
    subsetter.subset(font)
    if weights:
        # Round-trip through memory so every table is loaded before the axis is cut.
        font.flavor = None
        buf = io.BytesIO()
        font.save(buf)
        buf.seek(0)
        from fontTools.varLib import instancer

        font = instancer.instantiateVariableFont(TTFont(buf), {"wght": weights})
    font.flavor = "woff2"
    font.save(str(dst))


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--upstream", required=True, type=pathlib.Path)
    ap.add_argument("--out", type=pathlib.Path, default=HERE / "app" / "fonts")
    args = ap.parse_args(argv)
    up, out = args.upstream, args.out
    names = used_icons()
    reg_all = codepoints((up / "regular-style.css").read_text(encoding="utf-8"), "ph")
    fill_all = codepoints(
        (up / "fill-style.css").read_text(encoding="utf-8"), "ph-fill"
    )
    reg = {n: reg_all[n] for n in sorted(names) if n in reg_all}
    fill = {n: fill_all[n] for n in sorted(names) if n in fill_all}
    unknown = sorted(n for n in names if n not in reg_all and n not in fill_all)
    if unknown:
        print(
            "not in either icon font (left out): " + ", ".join(unknown), file=sys.stderr
        )
    out.mkdir(parents=True, exist_ok=True)
    subset(
        up / "regular-Phosphor.woff2", out / "phosphor.woff2", sorted(set(reg.values()))
    )
    subset(
        up / "fill-Phosphor-Fill.woff2",
        out / "phosphor-fill.woff2",
        sorted(set(fill.values())),
    )
    subset(
        up / "inter-latin.woff2",
        out / "inter-latin.woff2",
        INTER_POINTS,
        weights=(400, 500),
    )
    (out / "fonts.css").write_text(local_css(reg, fill), encoding="utf-8")
    print("icons: %d regular, %d fill" % (len(reg), len(fill)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
