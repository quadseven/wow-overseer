#!/usr/bin/env python3
"""Write docs/API.md from the route tables the servers actually serve.

Rows come from map_server.Handler.GET_ROUTES and apiv2.ROUTES, never typed
by hand. The summary and the query parameters are read from each handler's
first docstring line ("GET /path?key=X - what it answers"); a few v2 reads
that name their parameters further down are listed in EXTRA_PARAMS.

    python3 tools/gen_api_doc.py            # rewrite docs/API.md
    python3 tools/gen_api_doc.py --check    # exit 1 when it is stale
"""

from __future__ import annotations

import ast
import pathlib
import re
import sys
import types

ROOT = pathlib.Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "API.md"

# Parameters the first docstring line does not name.
EXTRA_PARAMS = {
    "/api/v2/series": ["name", "guild"],
    "/api/v2/dungeonups": ["family", "dungeon"],
}
# Served files, not answers: no handler docstring says what they are.
STATIC = {
    "/": "the operations app's page",
    "/index.html": "the operations app's page",
    "/shapes.json": "the character shape table the map draws from",
    "/jquery.min.js": "the page's bundled jQuery",
    "/manifest.webmanifest": "the installable app's manifest",
    "/apple-touch-icon.png": "the app's touch icon",
    "/icon-192.png": "the app's 192px icon",
    "/icon-512.png": "the app's 512px icon",
    "/healthz": "liveness: 200 while the server is up",
}
PLACEHOLDER = {
    "name": "Grug",
    "guild": "cave",
    "family": "grug",
    "limit": "20",
    "id": "1",
    "q": "grug",
    "entry": "1",
    "map": "1",
    "before": "1",
    "dungeon": "36",
}


def _split(doc: str) -> tuple[list[str], str]:
    """(parameter names, summary) from a docstring's first line."""
    first = (doc or "").strip().split("\n", 1)[0]
    first = re.sub(r"^GET\s+", "", first)
    head, summary = first, ""
    m = re.search(r"(?::\s|\s-\s)", first)
    if m:
        head, summary = first[: m.start()], first[m.end() :]
    params = list(dict.fromkeys(re.findall(r"(\w+)=", head)))
    return params, summary.strip()


def _module_doc(handler) -> str:
    module = sys.modules[handler.__module__]
    return ast.get_docstring(ast.parse(pathlib.Path(module.__file__).read_text())) or ""


def entries() -> list[dict]:
    sys.path.insert(0, str(ROOT))
    sys.modules.setdefault("pymysql", types.ModuleType("pymysql"))
    import apiv2
    import map_server

    out = []
    for path, handler in map_server.Handler.GET_ROUTES.items():
        params, summary = _split(handler.__doc__ or "")
        out.append(
            {"path": path, "params": params, "summary": summary or STATIC.get(path, "")}
        )
    for path, handler in apiv2.ROUTES.items():
        params, summary = _split(_module_doc(handler))
        params = list(dict.fromkeys(params + EXTRA_PARAMS.get(path, [])))
        out.append({"path": path, "params": params, "summary": summary})
    return sorted(out, key=lambda e: e["path"])


def example(entry: dict) -> str:
    args = " ".join(f"{p}={PLACEHOLDER.get(p, 'X')}" for p in entry["params"][:1])
    return f"overseer get {entry['path']} {args}".rstrip()


def render(items: list[dict]) -> str:
    lines = [
        "# Overseer read API",
        "",
        "Every GET route the map server answers. Generated by",
        "`tools/gen_api_doc.py` from `map_server.Handler.GET_ROUTES` and the",
        "`ROUTES` table of each `apiv2` module; do not edit by hand. A test",
        "fails when a served route is missing here. Read them with",
        "`tools/overseer` (set `OVERSEER_URL` to the server's base URL).",
        "",
        "Each entry: path, query parameters, what it answers, one example.",
        "",
    ]
    for e in items:
        params = ", ".join(f"`{p}`" for p in e["params"]) or "none"
        lines += [
            f"## `GET {e['path']}`",
            "",
            f"- Query: {params}",
            f"- Answers: {e['summary'] or 'see the handler'}",
            f"- Example: `{example(e)}`",
            "",
        ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = render(entries())
    if "--check" in argv:
        return 0 if DOC.exists() and DOC.read_text() == text else 1
    DOC.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
