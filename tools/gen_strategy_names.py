"""Write every strategy name a patched mod-playerbots tree can add.

WHY THIS EXISTS (#1298). The bridge asks for strategies by name (`co +flee`,
`nc +new rpg`, ...). Engine::addStrategy looks the name up in the bot's
strategy contexts and, when no context has a creator for it, does nothing at
all: the command is accepted, the bot answers, and nothing changes. Upstream
#2825 deleted the `flee` strategy, the deploy repo's roll 65 pinned that
build, and from then on every `co +flee` the bridge sent was a no-op that the
module's read-back reported as "CHANGED NOTHING" 32 times a member before
anyone looked. tests/test_strategy_names.py checks every name the bridge sends
against strategy_names.txt, which this script writes.

strategy_names.txt is generated, never edited by hand. Regenerate it whenever
the deploy repo moves AC_MODULE_SHA, or a patch under its
patches/mod-playerbots adds or renames a strategy:

  1. Check out quadseven/mod-playerbots at AC_MODULE_SHA.
  2. Apply the deploy repo's patches/mod-playerbots to it, in filename order,
     with zero fuzz (`patch -p1 -F0` per file). `retreat from danger` exists
     only in the patched tree (patch 0007).
  3. python3 tools/gen_strategy_names.py <patched tree> <AC_MODULE_SHA> \
       > tests/fixtures/strategy_names.txt

Each line is `<scope>\t<name>`. The scope is `all` for a strategy context
every bot carries (src/Ai/Base, Dungeon, Raid) and the class directory name,
lowercased, for one only that class's bots carry (src/Ai/Class/<Class>).

Stdlib only, no network.
"""

from __future__ import annotations

import pathlib
import re
import sys

# A strategy context is a NamedObjectContext<Strategy>; its constructor fills
# `creators`. Action and trigger contexts sit in the same files, so the class
# header is what tells them apart.
CONTEXT = re.compile(r"^class\s+\w+\s*:\s*public\s+NamedObjectContext<Strategy>", re.M)
CLASS_END = re.compile(r"^};", re.M)
CREATOR = re.compile(r'creators\[\s*"([^"]+)"\s*\]')


def scope_of(tree: pathlib.Path, path: pathlib.Path) -> str:
    parts = path.relative_to(tree).parts
    if len(parts) > 3 and parts[:3] == ("src", "Ai", "Class"):
        return parts[3].lower()
    return "all"


def collect(tree: pathlib.Path) -> set:
    """Return {(scope, name)} for every strategy creator in the tree."""
    sources = sorted(tree.glob("src/**/*.h")) + sorted(tree.glob("src/**/*.cpp"))
    if not sources:
        raise SystemExit(f"no sources under {tree / 'src'}")
    found = set()
    for path in sources:
        text = path.read_text(encoding="utf-8", errors="replace")
        for head in CONTEXT.finditer(text):
            end = CLASS_END.search(text, head.end())
            body = text[head.end() : end.start() if end else len(text)]
            for name in CREATOR.findall(body):
                found.add((scope_of(tree, path), name))
    if not any(scope == "all" for scope, _ in found):
        raise SystemExit("no shared strategy context found: is this mod-playerbots?")
    return found


def main(argv) -> int:
    if len(argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    tree, sha = pathlib.Path(argv[1]), argv[2]
    print("# Generated by tools/gen_strategy_names.py - do not edit by hand.")
    print(f"module {sha}")
    for scope, name in sorted(collect(tree)):
        print(f"{scope}\t{name}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
