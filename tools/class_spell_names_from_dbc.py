"""Generate the Standing card's names from the verified 3.3.5 client DBCs.

Usage: python3 tools/class_spell_names_from_dbc.py DBC_DIRECTORY > spellnames.js
Check success before replacing app/models/spellnames.js with that output.
The files come from wowgaming/client-data release v20.0, Data.zip/dbc.
Select every class skill line and class-restricted ability, at every level,
then include learn-spell wrappers recursively. No roster or level cap filters
this catalog. The trainer snapshot under tests/fixtures is coverage evidence,
not generation input. Checksums pin the same client data used by taughtspells.py.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
import struct
import sys

CHECKSUMS = {
    "Spell.dbc": "543b9fe61355b6a77a01714d52fea2e5",
    "SkillLine.dbc": "c4e4e914a868250dd087f37292d272d7",
    "SkillLineAbility.dbc": "d8c11abfcfe70596cb9068c0e97a1d9a",
}


def read_dbc(path: Path):
    blob = path.read_bytes()
    # Match published legacy version fingerprints, not an authenticity proof.
    if hashlib.md5(blob, usedforsecurity=False).hexdigest() != CHECKSUMS[path.name]:
        raise ValueError(f"{path.name}: does not match the documented client data")
    magic, count, fields, size, string_size = struct.unpack_from("<4s4I", blob)
    end = 20 + count * size
    if magic != b"WDBC" or size != fields * 4 or end + string_size != len(blob):
        raise ValueError(f"{path.name}: invalid DBC layout")
    rows = list(struct.iter_unpack(f"<{fields}I", blob[20:end]))
    return rows, blob[end:]


def class_spell_ids(skills, abilities, spells):
    # SkillLine.CategoryID 7 is CLASS. ClassMask also admits generic class
    # abilities such as armor proficiencies that are not in a class skill line.
    class_skills = {row[0] for row in skills if row[1] == 7}
    existing = {row[0] for row in spells}
    # Client ability rows can retain deleted spell IDs; those have no name.
    selected = {
        row[2]
        for row in abilities
        if (row[1] in class_skills or row[4]) and row[2] in existing
    }
    while True:
        wrappers = {
            row[0]
            for row in spells
            if any(row[71 + i] == 36 and row[116 + i] in selected for i in range(3))
        }
        if wrappers <= selected:
            return selected
        selected |= wrappers


def names_from_dbc(directory: Path):
    spells, strings = read_dbc(directory / "Spell.dbc")
    skills, _ = read_dbc(directory / "SkillLine.dbc")
    abilities, _ = read_dbc(directory / "SkillLineAbility.dbc")
    selected = class_spell_ids(skills, abilities, spells)
    names = {}
    for row in spells:
        if row[0] not in selected:
            continue
        # enUS SpellName and Rank string offsets in the 234-field 3.3.5 layout.
        name = strings[row[136] :].split(b"\0", 1)[0].decode("utf-8")
        rank = strings[row[153] :].split(b"\0", 1)[0].decode("utf-8")
        if not name:
            raise ValueError(f"class spell {row[0]} has no name")
        names[row[0]] = name + (f" ({rank})" if rank else "")
    return dict(sorted(names.items()))


def render(names):
    return (
        "// Generated by tools/class_spell_names_from_dbc.py; do not edit the table.\n"
        "// Verified 3.3.5 class skills, class-restricted abilities and learn wrappers.\n"
        "const SPELL_NAMES = "
        + json.dumps(names, ensure_ascii=True, indent=2)
        + ";\n\n"
        "export function classSpellName(spell) {\n"
        "  const id = Number(spell) || 0;\n"
        '  return SPELL_NAMES[id] || "Spell " + id;\n'
        "}\n\n"
        "export function wowheadSpellUrl(spell) {\n"
        '  return "https://www.wowhead.com/wotlk/spell=" + (Number(spell) || 0);\n'
        "}\n"
    )


if __name__ == "__main__":
    print(render(names_from_dbc(Path(sys.argv[1]))), end="")
