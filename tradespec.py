BLOCKED_SPEC = "spec"
UNREACHABLE = "unreachable"

# The order the five states are reported in, hardest-won first. Printed rather
# than implied, because a bar chart in this order reads as progress and in any
# other order reads as noise.
STATE_ORDER = (KNOWN, LEARNABLE, BLOCKED_SKILL, BLOCKED_SPEC, UNREACHABLE)

# What each state is CALLED on the page, and which of the stylesheet's four
# tones it is drawn in. Written here rather than in JavaScript for the reason
# test_recap_tab.ThePageDecidesNothing established and this whole view is held
# to: a word a reader acts on is a judgement, and a judgement composed on the
# page is one no Python test can reach. `tone` is a ROLE the stylesheet knows
# and never a colour - the site is drawn on two grounds and the stylesheet is
# the only thing that knows it.
STATE_WORDS = {
    KNOWN: ("known", "up"),
    LEARNABLE: ("learnable now", "up"),
    BLOCKED_SKILL: ("behind more skill", ""),
    BLOCKED_SPEC: ("behind a branch nobody took", "no"),
    UNREACHABLE: ("no route on this realm", "no"),
}

# And what a SPECIALIZATION in each state is called, which is a different set of
# words for the same five states because they describe a different thing. "known"
# is right for a recipe and wrong for a branch: a branch is HELD, and one whose
# rival is held is not merely unknown, it is shut for that character forever.
SPEC_WORDS = {
    KNOWN: ("held", "up"),
    LEARNABLE: ("ready to take", "up"),
    BLOCKED_SKILL: ("not yet", ""),
    BLOCKED_SPEC: ("closed off for good", "no"),
    UNREACHABLE: ("no route on this realm", "no"),
}

# AcquireMethod, out of SkillLineAbility.dbc and carried through craftbook.json.
# 0 is an explicit grant - a trainer purchase, a quest, a recipe item - and it
# PERSISTS to `character_spell`. 1 is auto-learned on a rank-up and is NEVER
# written back, because Player::_SaveSpells skips an UNCHANGED spell.
#
# THIS DISTINCTION IS LOAD-BEARING AND IT COST THIS PROJECT A DAY ALREADY.
# professions.py records the measurement: 0 of 457 tailors hold 2963 Bolt of
# Linen Cloth in `character_spell` and Og was WATCHED CASTING IT. So for an
# AcquireMethod 1 craft the spellbook cannot answer the question at all, and a
# completion figure that counted its absence as "missing" would report the
# family at a fraction of its real total, forever, with nothing failing. Every
# such craft at or under the holder's skill is counted KNOWN here, and the
# basis says it is counted rather than observed.
#
# THERE ARE THREE VALUES AND ONLY ONE OF THEM IS "EXPLICIT", which a first pass
# at this got wrong by testing for 1 alone. AzerothCore's own names for them are
# 0 (trained), SKILL_LINE_ABILITY_LEARNED_ON_SKILL_LEARN = 1 and
# SKILL_LINE_ABILITY_LEARNED_ON_SKILL_VALUE = 2, and 1 and 2 are the same kind
# of thing: the core grants them, nothing buys them, and `_SaveSpells` skips
# them for the same reason. Counted over the committed projection: 3622 rows at
# 0, 79 at 1 and exactly ONE at 2 (spell 10846, the Artisan First Aid rank).
# One row is precisely the shape of thing a test written against today's data
# would never catch, so the test is written against the RULE - anything that is
# not 0 is automatic - rather than against the two values that happen to occur.
ACQUIRE_TRAINED = 0
ACQUIRE_AUTOMATIC = 1
ACQUIRE_AUTOMATIC_AT_RANK = 2


def is_automatic(acquire: int) -> bool:
    """Does the core grant this craft rather than somebody buying it?

    The one question `character_spell` cannot answer, so it is asked HERE and
    before the spellbook is consulted. See ACQUIRE_TRAINED above for why it is
    a rule and not a pair of literals.
    """
    return int(acquire) != ACQUIRE_TRAINED


