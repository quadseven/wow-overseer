def load_craftbook(static_dir: str) -> dict:
    """The committed projection of every craft in the game, read once.

    THE SAME SHAPE THE OTHER THREE FROZEN BOOKS USE, and for the same reason
    armory.ItemBook and standing.StandingBook use it: the data is client DBC
    content that acore_world's own `skilllineability_dbc` does not carry (it is
    EMPTY on this realm, 0 rows, measured 2026-09-05), so a file is the only
    place it can come from.

    AN ABSENT FILE IS AN EMPTY BOOK AND NOT A CRASH. A worldserver image that
    predates this file, or a container built before it was added, must thin the
    Trades view rather than take the whole map server down - which is the guard
    the Trades endpoint already applies to a missing TABLE (infra#3172) applied
    to a missing FILE. An empty book produces no professions and the view says
    so, rather than a page of zeroes that reads like a family that knows
    nothing.
    """
    path = os.path.join(static_dir, CRAFTBOOK_FILE)
    try:
        with open(path, "r", encoding="utf-8") as handle:
            return json.load(handle)
    except (OSError, ValueError):
        return {}


# Spell.dbc effect ids, named so the catalogue's provenance comments can be
# read without a lookup. A SPECIALIZATION spell is effect 47 with nothing after
# it; the base profession spells (9785 "Blacksmithing", 10662 "Leatherworking")
# are effect 47 followed by 118 and are NOT specializations, which is the one
# way a naive "effect 47" scan goes wrong.
