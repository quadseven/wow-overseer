def _skill_word(skill: int) -> str:
    """The word for a skill id, out of the one table that has them."""
    for word, number in goals.SKILL_IDS.items():
        if number == int(skill):
            return word
    return "skill %d" % int(skill)


def specs_for_skill(skill: int) -> tuple:
    """Every specialization on one profession, in catalogue order."""
    return tuple(spec for spec in SPECS if spec.skill == int(skill))


def rivals_of(spec: Spec) -> tuple:
    """The specializations this one locks a single character out of.

    Keyed on the quest ExclusiveGroup, which is what the world actually
    enforces, rather than on "same profession": the three Master weapon
    sub-specs sit on blacksmithing beside Armorsmith and Weaponsmith and are
    NOT rivals of either - a Weaponsmith goes on to take one of them. Their
    rival_group is 0 and a 0 matches nothing, which is the honest answer and
    not an accident.
    """
    if not spec.rival_group:
        return ()
    return tuple(
        other
        for other in SPECS
        if other.rival_group == spec.rival_group and other.key != spec.key
    )


def chosen_spec(holder: str, slots: Sequence | None = None) -> Spec | None:
    """The specialization this character is meant to end up with, or None."""
    for slot in FAMILY_SLOTS if slots is None else slots:
        if slot.holder == holder:
            return BY_KEY[slot.spec_key]
    return None


def held_specs(spells: Sequence) -> tuple:
    """Which specializations a character's spellbook says they already hold.

    READ OFF THE SPECIALIZATION SPELL AND NOT THE GRANT. The grant is cast once
    by the quest and `character_spell` is not where it lands; the effect-47
    spell is the one the world keeps and the one every trainer row is gated on.

    Trustworthy in both directions here, and that is worth saying because it is
    NOT true of craft spells. professions.py's rule is to read
    SkillLineAbility.AcquireMethod before trusting `character_spell`, and every
    specialization spell is an explicit grant, so a row means held and no row
    means not held.
    """
    have = {int(spell) for spell in spells}
    return tuple(spec for spec in SPECS if spec.spell in have)


def spec_state(spec: Spec, value: int, level: int, held: Sequence) -> str:
    """Where one character stands on one specialization.

    Five answers and they must not collapse. A specialization already held is
    not the same as one a rival has closed off, and neither is the same as one
    the world has no route to for anybody - the last is a defect in the world
    data and the other two are progress.
    """
    if spec in held:
        return KNOWN
    if spec.unreachable:
        return UNREACHABLE
    if any(rival in held for rival in rivals_of(spec)):
        return BLOCKED_SPEC
    if int(level) < spec.req_level or int(value) < spec.req_rank:
        return BLOCKED_SKILL
    return LEARNABLE


def spec_line(
    spec: Spec, value: int, level: int, held: Sequence, holder: str, on_map: int
) -> str:
    """What stands between this character and this specialization, in one line.

    EVERY GATE IS NAMED SEPARATELY BECAUSE THEY FAIL DIFFERENTLY. Skill is
    ground out by crafting; a character level is ground out by playing; a
    continent is a refusal no amount of either clears; and a rival
    specialization is a door that has already shut. A sentence that said only
    "not yet" would flatten four different problems into one shrug.
    """
    state = spec_state(spec, value, level, held)
    word = _skill_word(spec.skill)
    if state == KNOWN:
        return "%s holds %s already" % (holder, spec.label)
    if state == UNREACHABLE:
        return "%s: %s" % (spec.label, spec.unreachable)
    if state == BLOCKED_SPEC:
        shut = ", ".join(rival.label for rival in rivals_of(spec) if rival in held)
        return (
            "%s can never take %s now: %s is exclusive with it and is "
            "already held" % (holder, spec.label, shut)
        )
    gates = []
    if int(value) < spec.req_rank:
        gates.append(
            "%s %d, and %s has %d, which is %d short"
            % (word, spec.req_rank, holder, int(value), spec.req_rank - int(value))
        )
    if int(level) < spec.req_level:
        gates.append(
            "character level %d, and %s is %d" % (spec.req_level, holder, int(level))
        )
    where = reach_line(spec, on_map, holder)
    if not gates:
        opening = (
            "%s meets everything quest %d %s asks for, and %s is who "
            "hands it over" % (holder, spec.quest, spec.quest_title, spec.npc_name)
        )
        return opening + (". " + where if where else "")
    return "quest %d %s asks for %s. %s is who hands it over%s" % (
        spec.quest,
        spec.quest_title,
        ", and ".join(gates),
        spec.npc_name,
        ". " + where if where else "",
    )


def reach_line(spec: Spec, on_map: int, holder: str) -> str:
    """Whether the NPC is on the continent this character is standing on.

    "" when it is, because a walk that is possible needs no sentence. A
    sentence when it is not, and it is a live measurement rather than a
    property of the specialization: professions.py's BLOCKERS records that this
    claim was quietly false for long enough to mislead an investigation, and
    the fix was to re-measure `characters.map` rather than to write it down.
    """
    if not on_map or int(on_map) == int(spec.npc_map):
        return ""
    return (
        "%s stands on map %d and %s is on map %d, which "
        "ResolveTravelTarget refuses outright: there is no navmesh across "
        "an ocean, so this is not a long walk, it is a refusal"
        % (spec.npc_name, spec.npc_map, holder, int(on_map))
    )


# ----------------------------------------------------------- the 100% figure --
#
# THE DENOMINATOR IS THE WHOLE PROBLEM, and it is why craftbook.json exists.
# `item_template` class 9 holds only the recipes that exist as an ITEM - a
# pattern off a vendor, a plan off a corpse - which is a minority of any
# profession: blacksmithing has 118 of them against 525 abilities on its skill
# line. A completion figure built on the item table would have read 100% while
# four hundred crafts were still unlearned, which is the exact class of
# false-green this repository keeps finding.
#
# So the denominator is every ability on the skill line, out of
# SkillLineAbility.dbc, and the numerator is counted against it.


def effective_rank(entry: Sequence, world_rank) -> int:
    """The skill a craft actually asks for, from the best source available.

    THE DBC FIELD NAMED "ReqSkillValue" IS NOT IT, and reading it as the gate
    is how a first pass at this concluded that Og, at tailoring 50, could learn
    421 of the 439 tailoring crafts in the game. Measured over craftbook.json:
    that field is 1 for 439 of 439 tailoring abilities, 508 of 525
    blacksmithing and 258 of 264 alchemy. It is not a rank, it is a floor
    nearly everything sits on.

    THE REAL GATE IS IN THE WORLD DATABASE, and it arrives here as
    `world_rank`: the lowest of `trainer_spell.ReqSkillRank` for every trainer
    that teaches it and `item_template.RequiredSkillRank` for the recipe item
    that carries it. The LOWEST, because those are alternative routes in and a
    craft is gated by the cheapest one, not by the dearest.

    THE FALLBACK IS THE YELLOW VALUE, for the handful of crafts the world
    database places nowhere - no trainer sells them and no item teaches them.
    `TrivialSkillLineRankLow` is the skill at which a craft stops granting a
    guaranteed point, so it is always at or above the true learn rank. Falling
    back to it can only UNDER-report what is learnable, and under-reporting is
    the only safe direction here: this number's whole job is to say when the
    family has reached 100%, and a gate set too low would let it say so early.
    """
    if world_rank is not None:
        return int(world_rank)
    return max(int(entry[1]), int(entry[2]))


def _craft_state(
    rank: int,
    acquire: int,
    gate: int,
    value: int,
    known_spells: frozenset,
    spell: int,
    held: Sequence,
) -> str:
    """Which of the five states one craft is in for one holder.

    THE ACQUIRE METHOD IS CHECKED BEFORE THE SPELLBOOK AND THE ORDER MATTERS.
    An AcquireMethod 1 craft is never written to `character_spell` at all, so
    asking the spellbook about one gets "no" forever however many times the
    character has cast it. professions.py measured this: 0 of 457 tailors hold
    2963 Bolt of Linen Cloth, and Og was watched casting it. A craft like that
    at or under the holder's skill is counted KNOWN, and the basis says counted
    rather than observed so nobody reads it as an observation.
    """
    if spell in known_spells:
        return KNOWN
    if gate:
        spec = BY_SPELL.get(gate)
        if spec is not None:
            if spec.unreachable:
                return UNREACHABLE
            if spec not in held:
                # A craft behind a specialization this character has not taken.
                # BLOCKED_SPEC whether the door is merely shut-for-now or shut
                # forever, because from the family's side both are "somebody
                # else has to take this branch", which is what a backup slot
                # is. The hierarchy is where the difference is spelled out.
                return BLOCKED_SPEC
    if is_automatic(acquire) and int(value) >= int(rank):
        return KNOWN
    if int(value) >= int(rank):
        return LEARNABLE
    return BLOCKED_SKILL


def _percent(known: int, total: int) -> int:
    """Whole percent, rounded DOWN, and never 100 unless it really is.

    Rounded down on purpose: 99.6% of a profession reported as 100% is the one
    number on this page a reader would act on and be wrong about, and the whole
    feature is a goal somebody is trying to finish.
    """
    if not total:
        return 0
    return min(100, (known * 100) // total)


def profession_completion(
    skill: int,
    crafts: Mapping,
    holders: Sequence,
    gates: Mapping,
    ranks: Mapping,
    known_by: Mapping,
    slots: Sequence | None = None,
) -> dict:
    """How far one profession is along the road to every recipe in it.

    `crafts` is craftbook.json's entry for this skill line: spell id -> [name,
    reqSkillValue, trivialLow, acquireMethod, createdItem]. `ranks` is spell id
    -> the skill the world actually asks for, and `gates` is spell id ->
    specialization spell; both come from the world database, where the trainer
    rows and the recipe items are the only two places either fact lives.

    THE BEST HOLDER IS WHO IT IS COUNTED AGAINST, singular, and that is a
    deliberate narrowing rather than a shortcut. "The guild knows this recipe"
    is a different question from "the guild's blacksmith knows this recipe",
    and only the second one is a road anybody is walking: a recipe known by a
    character who will never take blacksmithing again is not progress toward
    the family's blacksmith knowing it. With no holder at all every craft is
    BLOCKED_SKILL, which is the honest reading of a profession nobody has.
    """
    best = holders[0]["who"] if holders else ""
    value = int(holders[0]["value"]) if holders else 0
    known_spells = frozenset(known_by.get(best, ()))
    held = held_specs(known_spells)
    counts = {state: 0 for state in STATE_ORDER}
    for spell, entry in crafts.items():
        spell = int(spell)
        state = _craft_state(
            effective_rank(entry, ranks.get(spell)),
            int(entry[3]),
            int(gates.get(spell, 0)),
            value,
            known_spells,
            spell,
            held,
        )
        counts[state] += 1
    total = sum(counts.values())
    return {
        "skill": int(skill),
        "name": _skill_word(skill),
        "holder": best,
        "counts": counts,
        "total": total,
        "known": counts[KNOWN],
        "percent": _percent(counts[KNOWN], total),
        "line": _completion_line(_skill_word(skill), best, counts, total),
        "chips": _count_chips(counts),
    }


def _count_chips(counts: Mapping) -> list:
    """One chip per state that is not zero, in STATE_ORDER.

    A ZERO IS NOT DRAWN, and that is the whole reason this is a function rather
    than five fixed chips. "0 behind a branch nobody took" beside a profession
    with no branches at all is a chip that makes a reader look for something
    that is not there, and five of them on every row would bury the two that
    matter.
    """
    out = []
    for state in STATE_ORDER:
        if not counts.get(state):
            continue
        word, tone = STATE_WORDS[state]
        out.append({"text": "%d %s" % (counts[state], word), "tone": tone})
    return out


def _completion_line(word: str, holder: str, counts: Mapping, total: int) -> str:
    """One profession's standing, counted rather than judged.

    Every state that is non-zero is named. A sentence that reported only the
    percentage would hide WHICH wall the rest is behind, and the four walls
    need different answers: skill is crafting, a specialization is a second
    crafter, and unreachable is a world-data fix nobody here can make.
    """
    if not holder:
        return (
            "nobody holds %s, so all %d of its crafts are behind somebody "
            "taking the trade" % (word, total)
        )
    said = [
        "%s knows %d of the %d crafts on the %s skill line, which is %d%%"
        % (holder, counts[KNOWN], total, word, _percent(counts[KNOWN], total))
    ]
    if counts[LEARNABLE]:
        said.append(
            "%d more are under the skill already ground and are a "
            "trainer visit or a recipe away" % counts[LEARNABLE]
        )
    if counts[BLOCKED_SKILL]:
        said.append("%d sit above that skill" % counts[BLOCKED_SKILL])
    if counts[BLOCKED_SPEC]:
        said.append(
            "%d are behind a specialization this character has not "
            "taken, which needs a second crafter rather than more "
            "grinding" % counts[BLOCKED_SPEC]
        )
    if counts[UNREACHABLE]:
        said.append(
            "%d cannot be reached by anybody on this realm" % counts[UNREACHABLE]
        )
    return (
        ", and ".join(said)
        if len(said) == 1
        else (said[0] + ". " + "; ".join(said[1:]))
    )


def overall_line(professions_done: Sequence) -> str:
    """The one number the operator asked for, and what it is a fraction of."""
    total = sum(row["total"] for row in professions_done)
    known = sum(row["known"] for row in professions_done)
    if not total:
        return (
            "nothing here could read a craft list, so there is no "
            "completion figure to give"
        )
    return (
        "%d of %d crafts known across %d professions, which is %d%% of "
        "every recipe in the game for the trades this guild touches"
        % (known, total, len(professions_done), _percent(known, total))
    )


# -------------------------------------------------------------- the ladder --


def _slot_row(spec: Spec, holder: str, why: str, unlocks: int, exclusive: int) -> dict:
    """One rung, with what it is worth and who is on it."""
    return {
        "spec": spec.key,
        "label": spec.label,
        "skill": spec.skill,
        "profession": _skill_word(spec.skill),
        "holder": holder,
        "why": why,
        "unlocks": unlocks,
        "exclusive": exclusive,
        "family": bool(holder),
        "reachable": not spec.unreachable,
        "line": _slot_line(spec, holder, unlocks, exclusive),
        "chips": _rung_chips(spec, holder, unlocks),
    }


def _rung_chips(spec: Spec, holder: str, unlocks: int) -> list:
    """What a collapsed rung has to carry: whose it is, and what it is worth.

    THE FIRST CHIP IS THE ONE THAT MATTERS and it says which of three kinds of
    rung this is, because the ladder mixes all three and they call for
    completely different responses: a family rung is being walked toward, an
    empty one needs a person to recruit somebody, and an unreachable one needs
    a world-data fix nobody on this page can make.
    """
    if spec.unreachable:
        chips = [{"text": "no route on this realm", "tone": "no"}]
    elif holder:
        chips = [{"text": holder, "tone": "up"}]
    else:
        chips = [{"text": "nobody in this slot", "tone": "unsure"}]
    chips.append({"text": _skill_word(spec.skill), "tone": ""})
    chips.append(
        {
            "text": ("%d crafts" % unlocks) if unlocks != 1 else "1 craft",
            "tone": "" if unlocks else "unsure",
        }
    )
    return chips


def _slot_line(spec: Spec, holder: str, unlocks: int, exclusive: int) -> str:
    """What this rung is, said in the terms it matters in.

    A FAMILY RUNG AND A BACKUP RUNG ARE DIFFERENT SENTENCES because they are
    different KINDS of thing: one is a goal somebody is walking toward and the
    other is a hole in the roster. Writing both as "Armorsmith: 12 recipes"
    would let a reader take the second for the first, which is the whole
    mistake STEERING_LIMIT exists to stop.

    A RUNG WORTH NOTHING SAYS SO IN WORDS RATHER THAN PRINTING A ZERO. All
    three alchemy specializations gate no craft at all on this realm, and "0
    crafts" beside a rung reads like a page that failed to count rather than
    like a branch that genuinely adds no recipe. The distinction matters
    because the two call for opposite responses: one is a bug to fix and the
    other is a slot nobody should spend a recruit on.
    """
    what = ("%d crafts" % unlocks) if unlocks != 1 else "1 craft"
    if spec.unreachable:
        return "%s: %s are gated on it and nobody on this realm can take it. %s" % (
            spec.label,
            what,
            spec.unreachable,
        )
    if holder and not unlocks:
        return (
            "%s takes %s for the family, and it unlocks no recipe at all: "
            "this branch adds output to crafts they could already make, so "
            "it moves the completion figure by nothing and was chosen on "
            "what the family drinks rather than on what it can learn"
            % (holder, spec.label)
        )
    if holder:
        return "%s takes %s for the family, first in line for the %s behind it" % (
            holder,
            spec.label,
            what,
        )
    if not unlocks:
        return (
            "%s is an empty BACKUP SLOT that is not worth filling: it "
            "gates no craft on this realm, so recruiting for it would add "
            "nothing to the %d%% figure above" % (spec.label, 0)
        )
    return (
        "%s is a BACKUP SLOT with nobody in it: %s are behind it, and no "
        "member of the family can ever take it because the family's own %s "
        "has taken an exclusive rival branch. Only a recruited %s who "
        "chooses this branch can reach them"
        % (spec.label, what, _skill_word(spec.skill), _skill_word(spec.skill))
    )


def _order_line() -> str:
    """The rule the ladder is in, printed above it rather than implied.

    guildcraft._order's rule, and for the same reason: a list in an order is
    read as a finding whether or not anybody meant it to be.
    """
    return (
        "The family first, because they get first dibs: one rung each, in the "
        "order of how many crafts that specialization unlocks. Then the backup "
        "slots nobody fills, in the same order, so the biggest hole in the "
        "guild's recipe coverage is at the top. Then the specializations this "
        "realm has no route to at all, last, because no recruiting fills those. "
        "The count beside each rung is crafts gated on that specialization in "
        "trainer_spell and in the recipe items, counted live and not typed in."
    )


def hierarchy(gates: Mapping, slots: Sequence | None = None) -> list:
    """The cascading order, family first and backups after, worth-first within.

    `gates` is craft spell -> specialization spell, from the world's own
    `trainer_spell.ReqAbility1`. The COUNT beside each rung is derived from it
    rather than typed, so a rung cannot claim a worth the world disagrees with.
    """
    slots = FAMILY_SLOTS if slots is None else slots
    unlocks: dict = {}
    for gate in gates.values():
        unlocks[int(gate)] = unlocks.get(int(gate), 0) + 1

    by_holder = {slot.spec_key: slot for slot in slots}
    family = [
        _slot_row(
            BY_KEY[slot.spec_key],
            slot.holder,
            slot.why,
            unlocks.get(BY_KEY[slot.spec_key].spell, 0),
            unlocks.get(BY_KEY[slot.spec_key].spell, 0),
        )
        for slot in slots
    ]
    family.sort(key=lambda row: (-row["unlocks"], row["label"]))

    backups = []
    unreachable = []
    for key in _BACKUP_KEYS:
        spec = BY_KEY[key]
        if key in by_holder:
            continue
        row = _slot_row(
            spec, "", "", unlocks.get(spec.spell, 0), unlocks.get(spec.spell, 0)
        )
        (unreachable if spec.unreachable else backups).append(row)
    backups.sort(key=lambda row: (-row["unlocks"], row["label"]))
    unreachable.sort(key=lambda row: (-row["unlocks"], row["label"]))

    ladder = family + backups + unreachable
    for place, row in enumerate(ladder, start=1):
        row["rank"] = place
    return ladder


def coverage_gaps(holders_by_skill: Mapping) -> list:
    """The professions with nobody on them at all, which is the other kind of gap.

    A SPECIALIZATION GAP AND A PROFESSION GAP ARE NOT THE SAME HOLE. The first
    is "the family took the other branch"; the second is "nobody in this guild
    has this trade", and only the second can be answered by a family member
    changing their mind. professions.UNASSIGNED already names the two the
    family left open ON PURPOSE for a guild to cover, so those are reported as
    a decision rather than as a defect - the same distinction guildcraft's
    `_gap_line` makes, read from the same constant so the two cannot drift.
    """
    out = []
    for word in sorted(professions.CRAFTING):
        skill = goals.SKILL_IDS.get(word)
        if skill is None or holders_by_skill.get(skill):
            continue
        deliberate = word in professions.UNASSIGNED
        out.append(
            {
                "name": word,
                "skill": skill,
                "deliberate": deliberate,
                "line": (
                    "%s: nobody holds it, and the family's own trade table leaves "
                    "it open on purpose for the guild to cover, so it is a "
                    "decision waiting on members rather than a mistake" % word
                    if deliberate
                    else "%s: nobody in the guild holds it, so every craft on its skill "
                    "line is behind somebody taking the trade" % word
                ),
            }
        )
    return out


def craft_facts(craft_rows: Sequence) -> tuple:
    """(rank by spell, specialization gate by spell) out of the world's rows.

    `craft_rows` are the UNION of two reads that answer the same two questions
    about a craft from different tables: `trainer_spell` (what a trainer sells,
    at what rank, behind which specialization) and class-9 `item_template`
    (what a recipe item teaches, at what rank, behind which specialization).

    BOTH TABLES ARE NEEDED AND READING ONLY THE FIRST WAS A MEASURED MISTAKE.
    The three tailoring specializations gate NO trainer row at all - their
    crafts are recipe ITEMS carrying `RequiredSpell` - so a gate map built from
    `trainer_spell` alone reported Spellfire, Mooncloth and Shadoweave as
    unlocking zero crafts each, which is three false zeroes on the one page
    that exists to count. Weaponsmith was under-counted the same way, at 6
    instead of 9.

    THE LOWEST RANK WINS, because the rows are alternative routes to the same
    craft and the cheapest is the one that gates it. A craft sold by a trainer
    at 260 and carried by a world-drop pattern at 250 asks for 250.
    """
    ranks: dict = {}
    gates: dict = {}
    for row in craft_rows:
        spell = int(row.get("SpellId") or 0)
        if not spell:
            continue
        rank = row.get("ReqSkillRank")
        if rank is not None:
            rank = int(rank)
            if spell not in ranks or rank < ranks[spell]:
                ranks[spell] = rank
        gate = int(row.get("ReqAbility1") or 0)
        # Only a gate this catalogue recognises. `ReqAbility1` also carries
        # ordinary prerequisite spells - a rank-2 enchant requiring its rank-1 -
        # and reading one of those as a specialization would report a craft as
        # blocked behind a branch that does not exist.
        if gate in BY_SPELL:
            gates[spell] = gate
    return ranks, gates


def build_tradespec(
    craftbook: Mapping,
    craft_rows: Sequence,
    skill_rows: Sequence,
    spell_rows: Sequence,
    member_rows: Sequence,
    roster: Sequence,
    slots: Sequence | None = None,
) -> dict:
    """The whole view: the 100% figure, the ladder, and what stops both.

    `craftbook` is the committed projection of SkillLineAbility.dbc joined to
    Spell.dbc - every craft in the game per profession - and it is the
    DENOMINATOR. `craft_rows` are the world's own rows about those crafts: what
    rank each asks for and which specialization gates it. See `craft_facts`.

    EVERY ARGUMENT IS AN OBSERVATION HANDED IN, and nothing here goes and gets
    one. Same seam as professions.plan and guildcraft.build_guildcraft, and the
    same guarantee: this module has no path to the world, so it cannot invent a
    reading of it.
    """
    wanted = set(roster)
    levels = {row["name"]: int(row.get("level") or 0) for row in member_rows}
    maps = {row["name"]: int(row.get("map") or 0) for row in member_rows}
    known_by: dict = {}
    for row in spell_rows:
        if row["name"] in wanted:
            known_by.setdefault(row["name"], set()).add(int(row["spell"]))

    holders_by_skill: dict = {}
    for row in skill_rows:
        if row["name"] not in wanted:
            continue
        holders_by_skill.setdefault(int(row["skill"]), []).append(
            {
                "who": row["name"],
                "value": int(row.get("value") or 0),
                "max": int(row.get("max") or 0),
                "level": levels.get(row["name"], 0),
            }
        )
    for found in holders_by_skill.values():
        found.sort(key=lambda h: (-h["value"], -h["max"], h["who"]))

    ranks, gates = craft_facts(craft_rows)

    done = []
    for skill in sorted(int(key) for key in craftbook):
        crafts = craftbook[str(skill)]
        if not crafts:
            continue
        done.append(
            profession_completion(
                skill,
                crafts,
                holders_by_skill.get(skill, []),
                gates,
                ranks,
                known_by,
                slots,
            )
        )
    done.sort(key=lambda row: (-row["percent"], row["name"]))

    ladder = hierarchy(gates, slots)
    specs = _spec_cards(holders_by_skill, known_by, maps, slots)
    return {
        "line": overall_line(done),
        "percent": _percent(
            sum(row["known"] for row in done), sum(row["total"] for row in done)
        ),
        "professions": done,
        "specs": specs,
        "hierarchy": ladder,
        "order": _order_line(),
        "gaps": coverage_gaps(holders_by_skill),
        "limit_line": STEERING_LIMIT,
        "grant_line": GRANT_REFUSAL,
        # AN EMPTY BOOK AND A FAMILY THAT KNOWS NOTHING LOOK IDENTICAL FROM THE
        # PAGE, and only this sentence can keep them apart. craftbook.json is a
        # committed file, so it is absent exactly when a container was built
        # without it - and a row of 0% across fourteen professions is a claim
        # somebody would act on.
        "empty_note": (
            "craftbook.json could not be read, so there is no list "
            "of crafts to measure against and every figure here "
            "would be zero. That is a missing file in this "
            "container and not a guild that knows nothing."
            if not done
            else ""
        ),
        "basis": _basis(bool(gates)),
    }


def _spec_cards(
    holders_by_skill: Mapping,
    known_by: Mapping,
    maps: Mapping,
    slots: Sequence | None = None,
) -> list:
    """Each family member's own specialization, and what stands in the way."""
    out = []
    for slot in FAMILY_SLOTS if slots is None else slots:
        spec = BY_KEY[slot.spec_key]
        holders = holders_by_skill.get(spec.skill, [])
        mine = next((h for h in holders if h["who"] == slot.holder), None)
        value = mine["value"] if mine else 0
        level = mine["level"] if mine else 0
        held = held_specs(known_by.get(slot.holder, ()))
        state = spec_state(spec, value, level, held)
        word, tone = SPEC_WORDS[state]
        out.append(
            {
                "spec": spec.key,
                "label": spec.label,
                "holder": slot.holder,
                "profession": _skill_word(spec.skill),
                "skill": spec.skill,
                "quest": spec.quest,
                "quest_title": spec.quest_title,
                "npc": spec.npc_name,
                "state": state,
                "why": slot.why,
                "line": spec_line(
                    spec, value, level, held, slot.holder, maps.get(slot.holder, 0)
                ),
                "chips": [
                    {"text": word, "tone": tone},
                    {"text": _skill_word(spec.skill), "tone": ""},
                ],
            }
        )
    return out


def _basis(gated: bool) -> str:
    """What this view read, and the several things it is not saying.

    The house rule guildcraft._basis follows: the weakest claim goes first,
    because a reader who takes a counted number for an observed one will act on
    it.
    """
    gate_note = (
        "Which crafts sit behind a specialization is trainer_spell.ReqAbility1 "
        "in this realm's own world database, read live."
        if gated
        else "trainer_spell returned no ReqAbility1 rows this time, so NO craft is "
        "reported as specialization-gated. That is a missing read and not a "
        "profession without branches: the counts beside the hierarchy rungs "
        "will all be zero and should not be believed."
    )
    return (
        "THE COUNT OF WHAT IS KNOWN IS PART OBSERVED AND PART COUNTED, and the "
        "difference is not decoration. A craft whose SkillLineAbility "
        "AcquireMethod is 0 is an explicit grant and PERSISTS to "
        "character_spell, so a row there means known and no row means not "
        "known. A craft whose AcquireMethod is 1 is auto-learned on a rank-up "
        "and is NEVER written back, because Player::_SaveSpells skips an "
        "unchanged spell: measured on this realm, 0 of 457 tailors hold 2963 "
        "Bolt of Linen Cloth and one of the family was watched casting it. So "
        "an AcquireMethod 1 craft at or under the holder's skill is COUNTED as "
        "known here rather than observed, and the true figure could be lower "
        "if the world refuses one for a reason this page cannot see. "
        + gate_note
        + " The denominator is every ability on the profession's "
        "skill line out of SkillLineAbility.dbc, committed as craftbook.json "
        "by tools/craftbook_from_dbc.py and regenerated from the DBCs inside "
        "the running worldserver's own image. It is deliberately NOT "
        "item_template class 9, which holds only the recipes that exist as an "
        "ITEM: blacksmithing has 118 of those against 525 abilities, so a "
        "figure built on the item table would have read 100% with four hundred "
        "crafts unlearned. Completion is counted against ONE holder per "
        "profession, the one with the highest ground skill, because a recipe "
        "known by somebody who will never take the trade again is not progress "
        "toward the family's crafter knowing it. Percentages are rounded DOWN, "
        "so 100% means 100%."
    )
