"""The lifelong goal: every recipe in the game, and who is first in line for it.

WHAT WAS ASKED FOR, in the operator's own words: "the family should get first dibs
on the rarest recipes, they should have a life long goal of getting all possible
recipes, and then there should be designated backup guild members who do other
stuff... there's specializations for professions and I want Grug to be armor
blacksmith, and you can choose who will be the other master professions, sort of
cascading order if there's extra recipes."

Three things, and this module is the second and third of them. guildcraft.py
already answers "what can the guild make and where does a missing recipe come
from"; what it could not answer is "how far along the whole road are we" and
"who is first in line when two people want the same trade". Both of those turn
on SPECIALIZATIONS, which nothing in this repository knew about before.

WHY A SPECIALIZATION IS THE HINGE. A profession is not one tree. At a certain
skill and a certain character level, a blacksmith walks to one NPC and becomes
an Armorsmith or a Weaponsmith, and the choice is EXCLUSIVE and permanent
without an unlearn: the grant spell carries SPELL_EFFECT_UNLEARN_SPECIALIZATION
(133) alongside its learn, and the quests share an ExclusiveGroup. So one
character can never reach 100% of a profession's recipes. Twelve Armorsmith
plate recipes and nine Weaponsmith weapon recipes are, for one blacksmith, an
either/or forever. The ONLY route to all of them is a SECOND blacksmith who
takes the other branch, which is exactly the "designated backup guild members"
half of the request, and it is why the hierarchy below is a list of SLOTS and
not a list of people.

EVERYTHING IN THE CATALOGUE BELOW WAS MEASURED, AND ONE PIECE OF RECEIVED
WISDOM WAS MEASURED WRONG
--------------------------------------------------------------------------
The brief this was built from stated, from memory, that Grumnus Steelshaper is
the WEAPONSMITH trainer in Ironforge and that Seril Scourgebane is the
Armorsmith in Blackrock Depths. Both halves are false on this realm, and four
independent columns say so. Measured live 2026-09-14 against the wow-dev world
database and against the DBCs inside the running worldserver's own image
(mod-playerbots/azerothcore-wotlk 47960183bb03b83e8943eb2f0f39c16df9710c9d):

  creature_template.subname  5164 Grumnus Steelshaper is "Armorsmith Trainer";
                             11146 Ironus Coldsteel is "Weaponsmith Trainer".
  quest_template             5283 "The Art of the Armorsmith" has Grumnus as
                             BOTH its creature_queststarter and its
                             creature_questender. 5284 "The Way of the
                             Weaponsmith" has Ironus as both.
  quest RewardSpell          5283 rewards 9790, 5284 rewards 9789.
  Spell.dbc                  9790 is named "Armorsmith" and 9789 "Weaponsmith",
                             both effect 36 (LEARN_SPELL) + 133
                             (UNLEARN_SPECIALIZATION). The spells they teach
                             are 9788 "Armorsmith" and 9787 "Weaponsmith", both
                             effect 47 (TRADE_SKILL).
  trainer_spell.ReqAbility1  Grumnus's list (TrainerId 124) gates its crafts on
                             9788; Ironus's (123) gates on 9787.

Five columns, no disagreement. Seril Scourgebane (11193) is not an Armorsmith
anything: he stands in Everlook on map 1 with Kilram and Lilith the Lithe, and
the three of them are the MASTER WEAPON sub-specialists - see UNREACHABLE.

THE OFFSET BETWEEN A GRANT AND ITS SPECIALIZATION IS NOT CONSTANT, which is the
trap that makes "read one pair and infer the rest" wrong. Blacksmithing's grant
is spec+2, leatherworking's is spec+1, Gnomish Engineering's is spec+1 while
Goblin's is spec-1, Spellfire's is spec-1 while Mooncloth's is spec+1. Every
pair below was read out of Spell.dbc by name and cross-checked against the
quest's own RewardSpell column; none was inferred from another.

THE NUMBERS ARE NOT RESTATED ANYWHERE ELSE. `craftbook.json` (generated by
tools/craftbook_from_dbc.py) is the only place a craft spell's NAME and opening
rank live, and `trainer_spell.ReqAbility1` in the world database is the only
place a craft's specialization gate lives. This module holds the CATALOGUE -
which specialization exists, what grants it, what it costs and where the NPC
stands - and nothing that either of those two already answers.

WHAT THIS MODULE CANNOT DO, AND SAYS SO RATHER THAN QUIETLY NOT DOING IT. See
STEERING_LIMIT. Thirty-five of the forty guild members cannot be sent anywhere
by this system, so every backup slot below is a RECRUITING TARGET and a piece
of documentation, never an errand. A hierarchy that silently assumed otherwise
would be the "reports success while doing nothing" failure professions.py's own
BLOCKERS constant exists to prevent.
"""

