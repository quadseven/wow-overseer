def map_name(map_id) -> str:
    """The map's name, as the game says it; an id this client never had is
    named as an id, with the word "map" so it is never read as a count."""
    try:
        wanted = int(map_id)
    except (TypeError, ValueError):
        return "a map the row does not name"
    return MAP_NAMES.get(wanted) or "map %d" % wanted


def map_kind(map_id) -> str:
    """continent, city, dungeon, raid, battleground, arena or transport."""
    try:
        return MAP_KINDS.get(int(map_id), "")
    except (TypeError, ValueError):
        return ""


def is_instance(map_id) -> bool:
    """A map entered through a door, which a character enters and leaves."""
    return map_kind(map_id) in (DUNGEON, RAID, BATTLEGROUND, ARENA)


def zone_display(name: str) -> str:
    """zones.json's directory name as the game says it: "Ogrimmar" is
    Orgrimmar, "ShattrathCity" is Shattrath City."""
    name = str(name or "")
    if name in ZONE_NAMES:
        return ZONE_NAMES[name]
    out = ""
    for i, ch in enumerate(name):
        if i and ch.isupper() and name[i - 1].islower():
            out += " "
        out += ch
    return out


@lru_cache(maxsize=1)
def _geometry():
    from transform import Geometry

    return Geometry.load(HERE)


@lru_cache(maxsize=1)
def triggers() -> dict:
    """trigger id -> {map, x, y, to_map, to_x, to_y}, from triggers.json."""
    with open(os.path.join(HERE, "triggers.json")) as f:
        return {int(k): v for k, v in json.load(f).items()}


_NOT_TOWNS = ("Transport", "Flavor", "Quest")


@lru_cache(maxsize=1)
def _towns() -> tuple:
    """(map, x, y, "Town (Zone)") for every flight master named "Town, Zone".

    The node's own zone is used rather than the zone rectangles', which
    overlap: the Crossroads stands inside Mulgore's rectangle.
    """
    with open(os.path.join(HERE, "taxinodes.json")) as f:
        nodes = json.load(f)["nodes"]
    out = []
    for n in nodes:
        name = str(n.get("name") or "")
        if name.count(",") != 1 or name.startswith(_NOT_TOWNS) or " - " in name:
            continue
        town, zone = (part.strip() for part in name.split(","))
        out.append((int(n["map"]), float(n["x"]), float(n["y"]), (town, zone)))
    return tuple(out)


@lru_cache(maxsize=1)
def _doors() -> tuple:
    """(map, x, y, "the door of <instance>") for every doorway into an
    instance that stands on open ground."""
    return tuple(
        (
            int(t["map"]),
            float(t["x"]),
            float(t["y"]),
            "the door of " + map_name(t["to_map"]),
        )
        for t in triggers().values()
        if not is_instance(t["map"]) and is_instance(t["to_map"])
    )


def _nearest(points, map_id: int, x: float, y: float, yards: float):
    best, best_d = None, yards
    for m, px, py, name in points:
        if m != map_id:
            continue
        d = math.hypot(px - x, py - y)
        if d <= best_d:
            best, best_d = name, d
    return best


def zone_at(map_id, x, y) -> str:
    """The zone a point stands in, as the game names it; inside an instance,
    the instance.

    zones.json's rectangles overlap (Mulgore's covers the Wailing Caverns
    door in The Barrens), so when more than one holds the point, the zone of
    the nearest flight master breaks the tie, and the smallest wins after.
    """
    map_id = int(map_id)
    if map_kind(map_id) not in (CONTINENT, ""):
        return map_name(map_id)
    x, y = float(x), float(y)
    held = _zones_holding(map_id, x, y)
    if not held:
        return zone_display(_geometry().zone_name(map_id, x, y))
    if len(held) > 1:
        town = _nearest(_towns(), map_id, x, y, float("inf"))
        # A city is a zone of its own inside its land: "Orgrimmar, Durotar"
        # stands in Orgrimmar.
        for said in town or ():
            for name in held:
                if name.startswith(zone_display(said)):
                    return name
    return held[0]


def _zones_holding(map_id: int, x: float, y: float) -> list:
    """Display names of the zone rectangles holding a point, smallest first."""
    found = []
    for _, region in _geometry()._regions_for(map_id):
        for z in region["zones"]:
            if z["right"] <= y <= z["left"] and z["bottom"] <= x <= z["top"]:
                area = (z["left"] - z["right"]) * (z["top"] - z["bottom"])
                found.append((area, zone_display(z["name"])))
    return [name for _, name in sorted(found)]


def place_at(map_id, x, y) -> str:
    """A ground point as a reader would say it: "the Menethil Harbor docks
    (Wetlands)", "Menethil Harbor (Wetlands)", "Westfall", "The Deadmines"."""
    map_id = int(map_id)
    x, y = float(x), float(y)
    zone = zone_at(map_id, x, y)
    if map_kind(map_id) not in (CONTINENT, ""):
        return zone
    dock = _nearest(_doors() + DOCKS, map_id, x, y, DOCK_YARDS)
    if dock:
        return "%s (%s)" % (dock, zone)
    town = _nearest(_towns(), map_id, x, y, TOWN_YARDS)
    if not town:
        return zone
    name, town_zone = town
    # A city's flight master stands in the city: "Stormwind City", not
    # "Stormwind (Elwynn Forest)".
    if zone.startswith(name):
        return zone
    return "%s (%s)" % (name, zone_display(town_zone))


def parse_ground_aim(aim: str):
    """`at:<map>:<x>,<y>[,<z>]` as (map, x, y), or None."""
    text = str(aim or "").strip()
    if not text.startswith("at:"):
        return None
    head, _, rest = text[3:].partition(":")
    parts = rest.split(",")
    try:
        return int(head), float(parts[0]), float(parts[1])
    except (ValueError, IndexError):
        return None


def trigger_place(trigger_id) -> tuple[str, str]:
    """(how, place) for a teleporting doorway: ("out of", "Shadowfang Keep"),
    ("into", "The Deadmines") or ("through the portal to", "Darnassus").
    ("", "") for an id no teleport row holds."""
    try:
        row = triggers().get(int(trigger_id))
    except (TypeError, ValueError):
        row = None
    if not row:
        return "", ""
    here, there = int(row["map"]), int(row["to_map"])
    if is_instance(here) and not is_instance(there):
        return "out of", map_name(here)
    if is_instance(there):
        return "into", map_name(there)
    return "through the portal to", place_at(there, row["to_x"], row["to_y"])


def aim_place(aim: str) -> str:
    """Where a module aim points, named: a doorway by its instance, a ground
    point by its town and zone, `banker` as "the banker"."""
    text = str(aim or "").strip()
    if not text:
        return "nowhere"
    if text.startswith("trigger:"):
        how, place = trigger_place(text.split(":", 1)[1])
        if not place:
            return (
                "a doorway (trigger %s) the world database does not hold"
                % (text.split(":", 1)[1])
            )
        if how == "out of":
            return "the way out of " + place
        if how == "into":
            return "the door of " + place
        return "the portal to " + place
    ground = parse_ground_aim(text)
    if ground:
        return place_at(*ground)
    if text.startswith("at:"):
        return "a ground point the row does not spell whole (%s)" % text
    if text.isdigit():
        return "creature %s" % text
    return "the " + text


def walk_words(aim: str) -> str:
    """ "out of Shadowfang Keep", "into The Deadmines", "to Menethil Harbor
    (Wetlands)": the walk an aim asks for, after the verb."""
    text = str(aim or "").strip()
    if text.startswith("trigger:"):
        how, place = trigger_place(text.split(":", 1)[1])
        if place:
            return "%s %s" % (how, place)
    return "to " + aim_place(text)
