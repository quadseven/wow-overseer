"""Every place the realm can name: maps, zones, doorways and ground aims.

WHY THIS EXISTS. The site said "crossed into an unknown place" for a
character who had walked into The Deadmines, "walking to trigger 194" for a
party leaving Shadowfang Keep, and "a spot on the map" for an errand to the
Menethil Harbor docks. Each of those facts was on the row; only the name was
missing. zones.json holds the four continents and their zones and nothing
inside an instance, and acore_world's `map_dbc` table is empty (map names are
client data), so a lookup that asked only those two answered "unknown".

WHAT IT HOLDS.

  MAP_NAMES    every map of the 3.3.5 client's Map.dbc a character can stand
               on: continents, dungeons, raids, battlegrounds, arenas and the
               boats and zeppelins, by id. Frozen client data, so frozen here.
  ZONE_NAMES   zones.json's zone names are the client's directory names
               ("Ogrimmar", "Hilsbrad", "ShattrathCity"); this is what the game
               says out loud, the same table tools/gen_shapes.py draws with.
  triggers     triggers.json: every teleporting areatrigger (acore_world
               areatrigger joined to areatrigger_teleport, generated by
               tools/gen_triggers.py), with the map it stands on and the map it
               leads to.
  landmarks    taxinodes.json's flight masters ("Menethil Harbor, Wetlands")
               and DOCKS below: the town a ground aim stands in.

PURE apart from reading the committed JSON once.
"""

