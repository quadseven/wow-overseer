-- Prune the guild advertisements from the suggest_something speech class.
--
-- The rows below are in the seed for ai_playerbot_texts (class
-- suggest_something) in the playerbots module tree, at the module pin
-- recorded in UPSTREAM-PINS.env. A bot that already has a guild can be
-- handed any suggest_something line in guild chat, and each of these
-- lines asserts the speaker is looking for a guild it is already in:
--
--   id 741: %my_role is looking for guild.
--   id 743: %my_role wants to join a good guild.
--   id 801: any guilds willing to carry %my_role?
--   id 816: any leveling guilds out there?
--
-- Audit: those four are every guild search in the class. The seed holds
-- 134 suggest_something rows (ids 739 to 872); the only other guild
-- mentions in the table sit in other classes and say something else (a
-- guild recruiting outsiders, a guild that already ran, a trade with a
-- guild), so they are not this class's advertisements and stay.
--
-- Delete rather than rewrite: each row carries the same guild search in
-- its localized columns, so an English-only rewrite would leave the
-- advertisement speaking in every other language. The class keeps its
-- other 130 lines, and ai_playerbot_texts_chance is keyed by class name
-- (this class has no chance row in the seed), so deleting the rows
-- orphans nothing.
--
-- The SQL that changes the live rows is this file: applying it through
-- the worldserver DB updater deletes exactly the four rows listed
-- above, each guarded to the suggest_something class.
DELETE FROM `ai_playerbot_texts`
WHERE `name` = 'suggest_something'
  AND `id` IN (741, 743, 801, 816);
